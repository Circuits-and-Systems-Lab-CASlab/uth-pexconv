import filecmp
import os
import subprocess
import sys
from pathlib import Path

import pytest

# test_universal2fastercap.py
#
# Two levels of coverage, per plan:
#   1. Smoke test - the converter runs to completion on a known input
#      pattern and produces the expected output file structure, without
#      checking exact contents. Cheap, catches crashes/exceptions.
#   2. Golden test - full byte-for-byte diff of every output file (the
#      .lst pattern file plus every Dielectrics/ and Wires/ panel file)
#      against a committed known-good copy in tests/golden/.
#
# The golden fixture (tests/golden/) was generated by running the
# converter on tests/fixtures/universal_input/Test1/wires with output
# folder name "output" (relative), standard heights, 3D mode. If you
# change TEST1_OUTPUT_DIR_NAME below, you must regenerate tests/golden/
# to match - the D/C record lines in wires.lst embed this folder name
# literally as part of `currentpath`, so a name mismatch will show up
# as a spurious diff on every single output file, not a real bug.
#
# KT-NOTE: To regenerate the golden file:
#   cd converters/fastercap/src
#   python3 Universal2FasterCap.py ../../../tests/fixtures/universal_input <tmp>/output standard 3D

THIS_DIR = Path(__file__).parent
FIXTURES_DIR = THIS_DIR / "fixtures"
GOLDEN_DIR = THIS_DIR / "golden"
CONVERTER_SRC_DIR = THIS_DIR.parent / "src"  # converters/fastercap/src/

TEST1_UNIVERSAL_INPUT = FIXTURES_DIR / "universal_input"
TEST1_OUTPUT_DIR_NAME = "output"  # must match how tests/golden/ was generated


def run_converter(universal_input_dir: Path, cwd: Path) -> subprocess.CompletedProcess:
    # Invoke Universal2FasterCap.py as a subprocess, same as command-line usage

    return subprocess.run(
        [
            sys.executable,
            str(CONVERTER_SRC_DIR / "Universal2FasterCap.py"),
            str(universal_input_dir),
            TEST1_OUTPUT_DIR_NAME,
            "standard",
            "3D",
        ],
        capture_output=True,
        text=True,
        cwd=str(cwd),
    )


def all_files_relative(root: Path) -> set:
    return {str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()}


class TestSmoke:
    def test_runs_without_error(self, tmp_path):
        result = run_converter(TEST1_UNIVERSAL_INPUT, cwd=tmp_path)
        assert result.returncode == 0, (
            f"Converter exited non-zero.\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )

    def test_produces_expected_lst_file(self, tmp_path):
        run_converter(TEST1_UNIVERSAL_INPUT, cwd=tmp_path)
        output_dir = tmp_path / TEST1_OUTPUT_DIR_NAME
        assert (output_dir / "Test1" / "wires.lst").exists()

    def test_produces_dielectrics_and_wires_panel_folders(self, tmp_path):
        run_converter(TEST1_UNIVERSAL_INPUT, cwd=tmp_path)
        output_dir = tmp_path / TEST1_OUTPUT_DIR_NAME
        assert (output_dir / "Dielectrics").is_dir()
        assert (output_dir / "Wires").is_dir()
        assert any((output_dir / "Dielectrics").iterdir())
        assert any((output_dir / "Wires").iterdir())


class TestGolden:
    def test_output_matches_golden_file_list(self, tmp_path):
        run_converter(TEST1_UNIVERSAL_INPUT, cwd=tmp_path)
        output_dir = tmp_path / TEST1_OUTPUT_DIR_NAME

        actual_files = all_files_relative(output_dir)
        golden_files = all_files_relative(GOLDEN_DIR)

        missing = golden_files - actual_files
        extra = actual_files - golden_files
        assert not missing, f"Files present in golden but missing from output: {sorted(missing)}"
        assert not extra, f"Files present in output but not in golden (new/renamed?): {sorted(extra)}"

    def test_output_matches_golden_byte_for_byte(self, tmp_path):
        run_converter(TEST1_UNIVERSAL_INPUT, cwd=tmp_path)
        output_dir = tmp_path / TEST1_OUTPUT_DIR_NAME

        golden_files = sorted(all_files_relative(GOLDEN_DIR))
        mismatches = []
        for rel_path in golden_files:
            golden_file = GOLDEN_DIR / rel_path
            actual_file = output_dir / rel_path
            if not actual_file.exists():
                mismatches.append(f"{rel_path}: MISSING from output")
                continue
            if not filecmp.cmp(golden_file, actual_file, shallow=False):
                mismatches.append(f"{rel_path}: content differs")

        assert not mismatches, (
            "Output differs from golden for "
            f"{len(mismatches)} file(s):\n" + "\n".join(mismatches) +
            "\n\nIf this difference is intentional (a real behavior change, "
            "not a regression), regenerate tests/golden/ per the "
            "instructions at the top of this file - do not just accept "
            "a diff you haven't explained."
        )
